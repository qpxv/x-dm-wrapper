// How I want sales conversations to typically go. The AI should use this as a
// playbook for qualifying prospects and steering the conversation naturally.
export const SALES_SOP = `10 Chill Questions to Qualify a Prospect (Without Sounding Salesy)

1. "Curious — what got you into this business in the first place?"
-> Builds rapport + shows genuine interest.

2. "What kind of clients do you usually work with?"
-> Reveals niche + offer clarity.

3. "How's business been lately — steady or kind of up and down?"
-> Surfaces consistency problems naturally.

4. "Do most people find you online or through word of mouth?"
-> Tells you how they get clients (without sounding probing).

5. (If online) "Nice — where do they usually come from? Like socials, content, ads?"
   (If referrals) "Ah nice, referrals are solid — but kinda unpredictable sometimes, right?"
-> Makes them voice the pain themselves.

6. "When someone's interested, how do they usually reach out? DM, email, book a call?"
-> Checks their funnel flow.

7. "Do you send people to a site or just handle it all through social/DMs?"
-> Brings up website/systems naturally.

8. "Does that setup work well, or do you ever feel like people drop off along the way?"
-> Surfaces conversion pain points.

9. "If everything ran smooth and clients were just rolling in — what would that look like for you?"
-> Gets them to describe their dream system (aka your solution).

10. "Gotcha — makes sense. I've been helping a few businesses like yours tighten that part up — want me to share a few ideas?"
-> Non-pushy transition to your offer.

General approach: work through these naturally over the course of the conversation, not
as a rigid script — pick whichever question fits where the conversation actually is. Keep
it chill and curious, not interrogative. Let the prospect surface their own pain points
before pitching anything. Only pivot to the offer once real pain has been voiced. Applies
to any type of prospect — coaches, consultants, agencies, and other service businesses —
so keep language generic and adapt naturally to whatever business the prospect is in.`;
